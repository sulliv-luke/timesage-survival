"""Characterisation of ``timesage._ipcw`` against golden outputs of the original code.

Goldens: ``tests/fixtures/golden/ipcw_legacy.npz`` (metadata in the ``.json``
sidecar), generated by running ``time_sage_survival.py`` of the original
research implementation:

- ``fit_censoring_km``       -> ``fit_censoring_km``
- ``CensoringKM.G``          -> ``CensoringKM.__call__``
- ``ipcw_brier_loss_multi``  -> ``ipcw_brier_loss``
- ``ipcw_brier_loss_vector`` -> ``ipcw_brier_loss`` with one time point

Inputs are synthetic and cover continuous times, heavy ties (including
event/censoring ties), no censoring, a censored largest time (``G_hat`` reaches
0 and is clipped to 1e-12) and all-censored data.

Tolerance: level L0 of ``tests/parity/tolerances.toml``. The port performs the
same float64 operations in the same order, so in practice the outputs are
bit-identical; L0 leaves room only for rounding-order differences.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pytest

from timesage._ipcw import fit_censoring_km, ipcw_brier_loss

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "ipcw_legacy.npz"
TOLERANCES = Path(__file__).resolve().parents[1] / "parity" / "tolerances.toml"
CASES = ["continuous", "ties", "no_censoring", "tail_zero", "all_censored"]

# Must equal [L0_exact] in tests/parity/tolerances.toml (checked below on 3.11+).
L0_RTOL = 1e-10
L0_ATOL = 1e-12


@pytest.fixture(scope="module")
def golden() -> dict[str, np.ndarray]:
    with np.load(GOLDEN) as z:
        return {k: z[k] for k in z.files}


def _assert_l0(actual: np.ndarray, expected: np.ndarray) -> None:
    np.testing.assert_allclose(actual, expected, rtol=L0_RTOL, atol=L0_ATOL)


@pytest.mark.skipif(sys.version_info < (3, 11), reason="tomllib needs Python 3.11")
def test_tolerance_constants_match_tolerances_toml() -> None:
    import tomllib

    level = tomllib.loads(TOLERANCES.read_text(encoding="utf-8"))["L0_exact"]
    assert (level["rtol"], level["atol"]) == (L0_RTOL, L0_ATOL)


@pytest.mark.parametrize("case", CASES)
def test_km_step_function_matches_legacy(golden: dict[str, np.ndarray], case: str) -> None:
    km = fit_censoring_km(golden[f"{case}/T"], golden[f"{case}/delta"])
    _assert_l0(km.times, golden[f"{case}/km_times"])
    _assert_l0(km.survival, golden[f"{case}/km_surv"])


@pytest.mark.parametrize("case", CASES)
def test_km_evaluation_matches_legacy(golden: dict[str, np.ndarray], case: str) -> None:
    T = golden[f"{case}/T"]
    km = fit_censoring_km(T, golden[f"{case}/delta"])
    _assert_l0(km(golden[f"{case}/query"]), golden[f"{case}/G_query"])
    _assert_l0(km(golden[f"{case}/grid"]), golden[f"{case}/G_grid"])
    scalar = km(float(np.median(T)))
    assert scalar.shape == ()
    _assert_l0(scalar, golden[f"{case}/G_scalar"])


@pytest.mark.parametrize("case", CASES)
def test_ipcw_brier_loss_matches_legacy(golden: dict[str, np.ndarray], case: str) -> None:
    T, delta = golden[f"{case}/T"], golden[f"{case}/delta"]
    grid, pred = golden[f"{case}/grid"], golden[f"{case}/pred"]
    km = fit_censoring_km(T, delta)
    _assert_l0(ipcw_brier_loss(pred, T, delta, grid, km), golden[f"{case}/loss_multi"])
    # Passing precomputed G_hat(t_k), as the original estimator does.
    _assert_l0(
        ipcw_brier_loss(pred, T, delta, grid, km, censoring_at_times=km(grid)),
        golden[f"{case}/loss_multi"],
    )


@pytest.mark.parametrize("case", CASES)
def test_single_time_loss_matches_legacy_vector_loss(
    golden: dict[str, np.ndarray], case: str
) -> None:
    T, delta = golden[f"{case}/T"], golden[f"{case}/delta"]
    grid, pred = golden[f"{case}/grid"], golden[f"{case}/pred"]
    km = fit_censoring_km(T, delta)
    for k in (0, len(grid) // 2, len(grid) - 1):
        loss_k = ipcw_brier_loss(pred[:, [k]], T, delta, grid[[k]], km)
        _assert_l0(loss_k[:, 0], golden[f"{case}/loss_vector"][:, k])

"""Characterisation of the public ``TimeSAGE`` estimator against the original ``TimeSAGE.fit``.

Goldens: ``tests/fixtures/golden/estimator_legacy.npz`` (metadata in the
``.json`` sidecar), generated by running the original research
implementation:

- the original ``TimeSAGE(...).fit(X, T, delta, times, background_data=bg)`` with
  ``joint_times=True`` -> ``TimeSAGE(model, background=bg, ...).explain(X, T, delta, times)``;
- the synthetic study's background subsampling (``timesage_runner.py``) ->
  ``TimeSAGE(..., n_background=96, random_state=seed)``;
- the original empty-coalition loss (``timesage_runner._loss_curves``) ->
  ``TimeSAGEResult.loss_empty``.

Tolerance: L0 (``tests/parity/tolerances.toml``). RNG draw order and
floating-point operation order are unchanged, so the outputs are bit-identical
in practice. ``loss_full`` is not compared: the original implementation
computed it from float64
inputs, the package from the estimator's float32 inputs (by design).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from tests.fixtures.toy_models import toy_predict_survival
from timesage import TimeSAGE

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "estimator_legacy.npz"

# Must equal [L0_exact] in tests/parity/tolerances.toml
# (checked in tests/characterisation/test_ipcw.py).
L0_RTOL = 1e-10
L0_ATOL = 1e-12


@pytest.fixture(scope="module")
def golden() -> dict[str, np.ndarray]:
    with np.load(GOLDEN) as z:
        return {k: z[k] for k in z.files}


def _assert_l0(actual: np.ndarray, expected: np.ndarray) -> None:
    np.testing.assert_allclose(actual, expected, rtol=L0_RTOL, atol=L0_ATOL)


def _explain(golden: dict[str, np.ndarray], **kwargs: object):
    explainer = TimeSAGE(toy_predict_survival, background=golden["background"], **kwargs)  # type: ignore[arg-type]
    return explainer.explain(golden["X"], golden["T"], golden["delta"], golden["times"])


def test_exact_budget_matches_legacy_fit(golden: dict[str, np.ndarray]) -> None:
    res = _explain(golden, n_permutations=256, batch_size=64, random_state=7)
    _assert_l0(res.phi, golden["exact/values"])
    _assert_l0(res.phi_se, golden["exact/std"])
    _assert_l0(res.loss_empty, golden["exact/loss_empty"])
    assert res.n_permutations == 256
    assert res.converged is None


def test_early_stopping_matches_legacy_fit(golden: dict[str, np.ndarray]) -> None:
    res = _explain(
        golden,
        n_permutations=4096,
        batch_size=32,
        convergence_threshold=float(golden["converge/thresh"]),
        random_state=11,
    )
    assert res.converged is True
    assert res.n_permutations == int(golden["converge/n_permutations"])
    _assert_l0(res.phi, golden["converge/values"])
    _assert_l0(res.phi_se, golden["converge/std"])


def test_background_subsampling_matches_synthetic_runner(golden: dict[str, np.ndarray]) -> None:
    seed = int(golden["subsample/seed"])
    X_train = golden["subsample/X_train"]
    explainer = TimeSAGE(
        toy_predict_survival,
        background=X_train,
        n_background=96,
        n_permutations=128,
        batch_size=64,
        random_state=seed,
    )
    np.testing.assert_array_equal(
        explainer.background, X_train[golden["subsample/bg_idx"]].astype(np.float32)
    )
    res = explainer.explain(
        golden["subsample/X"],
        golden["subsample/T"],
        golden["subsample/delta"],
        golden["subsample/times"],
    )
    _assert_l0(res.phi, golden["subsample/values"])
    _assert_l0(res.phi_se, golden["subsample/std"])

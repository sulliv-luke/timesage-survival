"""Characterisation of ``timesage._value`` against the original value function.

Goldens: ``tests/fixtures/golden/value_legacy.npz`` (metadata in the ``.json``
sidecar), generated by running the original research implementation:

- ``TimeSAGE._fit_joint`` closures (``model_all_times`` with ``MarginalImputer``,
  and ``loss_multi``) -> ``timesage._value.CoalitionValue.predict`` / ``.loss``

The model is ``tests/fixtures/toy_models.py:toy_predict_survival``. Inputs are
float32-cast as in the original ``TimeSAGE.fit``.

Tolerance: L0 (``tests/parity/tolerances.toml``). The arithmetic is unchanged,
so in practice the outputs are bit-identical.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from tests.fixtures.toy_models import toy_predict_survival
from timesage._ipcw import fit_censoring_km
from timesage._value import CoalitionValue

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "value_legacy.npz"

# Must equal [L0_exact] in tests/parity/tolerances.toml
# (checked in tests/characterisation/test_ipcw.py).
L0_RTOL = 1e-10
L0_ATOL = 1e-12


@pytest.fixture(scope="module")
def golden() -> dict[str, np.ndarray]:
    with np.load(GOLDEN) as z:
        return {k: z[k] for k in z.files}


def _assert_l0(actual: np.ndarray, expected: np.ndarray) -> None:
    np.testing.assert_allclose(actual, expected, rtol=L0_RTOL, atol=L0_ATOL)


def _value(golden: dict[str, np.ndarray]) -> CoalitionValue:
    km = fit_censoring_km(golden["T"], golden["delta"])
    background = np.asarray(golden["background"], np.float32)
    return CoalitionValue(toy_predict_survival, background, golden["times"], km)


def test_value_function_matches_legacy_closures(golden: dict[str, np.ndarray]) -> None:
    # One CoalitionValue reused across batches of different sizes, as the
    # original reused one imputer (this exercises its cached background tiling).
    value = _value(golden)
    X32 = np.asarray(golden["X"], np.float32)
    for b in range(4):
        idx, mask = golden[f"batch{b}/idx"], golden[f"batch{b}/mask"]
        pred = value.predict(X32[idx], mask)
        _assert_l0(pred, golden[f"batch{b}/pred"])
        loss = value.loss(X32[idx], mask, golden["T"][idx], golden["delta"][idx])
        _assert_l0(loss, golden[f"batch{b}/loss"])

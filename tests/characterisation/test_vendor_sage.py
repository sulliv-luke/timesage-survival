"""Characterisation of the vendored sage classes against sage-importance 0.0.6.

Goldens: ``tests/fixtures/golden/value_legacy.npz`` (metadata in the ``.json``
sidecar), generated by running the original research implementation:

- ``sage.imputers.MarginalImputer`` -> ``timesage._vendor.sage.MarginalImputer``
- ``sage.utils.ImportanceTracker``  -> ``timesage._vendor.sage.ImportanceTracker``

The model is ``tests/fixtures/toy_models.py:toy_predict_survival``. Inputs are
float32-cast as in the original ``TimeSAGE.fit``.

Tolerance: L0 (``tests/parity/tolerances.toml``). The arithmetic is unchanged,
so in practice the outputs are bit-identical.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from tests.fixtures.toy_models import toy_predict_survival
from timesage._vendor.sage import ImportanceTracker, MarginalImputer

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "value_legacy.npz"

# Must equal [L0_exact] in tests/parity/tolerances.toml
# (checked in tests/characterisation/test_ipcw.py).
L0_RTOL = 1e-10
L0_ATOL = 1e-12


@pytest.fixture(scope="module")
def golden() -> dict[str, np.ndarray]:
    with np.load(GOLDEN) as z:
        return {k: z[k] for k in z.files}


def _assert_l0(actual: np.ndarray, expected: np.ndarray) -> None:
    np.testing.assert_allclose(actual, expected, rtol=L0_RTOL, atol=L0_ATOL)


def test_vendored_imputer_matches_sage(golden: dict[str, np.ndarray]) -> None:
    times = golden["times"]
    X32 = np.asarray(golden["X"], np.float32)
    imputer = MarginalImputer(
        lambda x: toy_predict_survival(x, times), np.asarray(golden["background"], np.float32)
    )
    for b in range(4):
        idx, mask = golden[f"batch{b}/idx"], golden[f"batch{b}/mask"]
        _assert_l0(imputer(X32[idx], mask), golden[f"batch{b}/pred"])


def test_vendored_imputer_float64_background_matches_sage(
    golden: dict[str, np.ndarray],
) -> None:
    # The original TimeSAGE.fit with background_data=None: float64 background, float32 rows.
    times = golden["times"]
    X = golden["X"]
    imputer = MarginalImputer(lambda x: toy_predict_survival(x, times), X[:24])
    pred = imputer(np.asarray(X[:40], np.float32), golden["bg64/mask"])
    _assert_l0(pred, golden["bg64/pred"])


@pytest.mark.parametrize("kind", ["dense", "sparse"])
def test_vendored_importance_tracker_matches_sage(golden: dict[str, np.ndarray], kind: str) -> None:
    tracker = ImportanceTracker()
    for u in range(3):
        scores = golden[f"tracker_{kind}/scores{u}"]
        if kind == "dense":
            tracker.update(scores)
        else:
            tracker.update(scores, golden[f"tracker_sparse/num_samples{u}"])
        _assert_l0(tracker.values, golden[f"tracker_{kind}/mean{u}"])
        _assert_l0(tracker.std, golden[f"tracker_{kind}/std{u}"])

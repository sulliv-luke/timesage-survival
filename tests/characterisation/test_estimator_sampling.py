"""Characterisation of the permutation sampler against the original estimator.

Goldens: ``tests/fixtures/golden/estimator_legacy.npz`` (metadata in the
``.json`` sidecar), generated by running the original research
implementation:

- the original ``TimeSAGE.fit`` (joint times) -> ``timesage.estimator._sample_permutations``
  on a ``CoalitionValue`` built as the original ``fit`` builds its value function.

Cases: exact B with ``n_jobs=1`` and with ``n_jobs=2`` (identical in the original),
and early stopping. Every case uses a budget that is a multiple of the batch
size, so the original implementation's rounding does not apply.

Tolerance: L0 (``tests/parity/tolerances.toml``) rather than L1, because the
RNG draw order and the floating-point operation order are both unchanged. In
practice the outputs are bit-identical.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from tests.fixtures.toy_models import toy_predict_survival
from timesage._ipcw import fit_censoring_km
from timesage._value import CoalitionValue
from timesage.estimator import _sample_permutations

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "estimator_legacy.npz"

# Must equal [L0_exact] in tests/parity/tolerances.toml
# (checked in tests/characterisation/test_ipcw.py).
L0_RTOL = 1e-10
L0_ATOL = 1e-12


@pytest.fixture(scope="module")
def golden() -> dict[str, np.ndarray]:
    with np.load(GOLDEN) as z:
        return {k: z[k] for k in z.files}


def _assert_l0(actual: np.ndarray, expected: np.ndarray) -> None:
    np.testing.assert_allclose(actual, expected, rtol=L0_RTOL, atol=L0_ATOL)


def _run(golden: dict[str, np.ndarray], **kwargs: object):
    T, delta = golden["T"], golden["delta"]
    value = CoalitionValue(
        toy_predict_survival, golden["background"], golden["times"], fit_censoring_km(T, delta)
    )
    x = np.asarray(np.asarray(golden["X"], float), np.float32)  # the original fit's casts
    return _sample_permutations(value, x, T, delta.astype(int), **kwargs)  # type: ignore[arg-type]


@pytest.mark.parametrize("case", ["exact", "njobs2"])
def test_exact_budget_matches_legacy(golden: dict[str, np.ndarray], case: str) -> None:
    out = _run(golden, n_permutations=256, batch_size=64, convergence_threshold=None, seed=7)
    _assert_l0(out.values, golden[f"{case}/values"])
    _assert_l0(out.std, golden[f"{case}/std"])
    assert out.n_permutations == int(golden[f"{case}/n_permutations"]) == 256
    assert out.converged is None


def test_early_stopping_matches_legacy(golden: dict[str, np.ndarray]) -> None:
    out = _run(
        golden,
        n_permutations=4096,
        batch_size=32,
        convergence_threshold=float(golden["converge/thresh"]),
        seed=11,
    )
    assert out.converged is True
    assert out.n_permutations == int(golden["converge/n_permutations"])
    _assert_l0(out.values, golden["converge/values"])
    _assert_l0(out.std, golden["converge/std"])

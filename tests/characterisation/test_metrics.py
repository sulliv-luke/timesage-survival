"""Characterisation of ``timesage.metrics`` against the original synthetic-study metrics.

Goldens: ``tests/fixtures/golden/metrics_legacy.npz`` (metadata in the
``.json`` sidecar), generated by running the original research
implementation on synthetic curves.

Mapping (original -> package):

- ``truth.stable_support_mask(times, T_train, E_train, T_test)`` ->
  ``stable_window(times, T_test, E_test, censoring_time=T_train,
  censoring_event=E_train, legacy_parity=True)``;
- ``_safe_corr("pearson", est[m], ref[m])`` -> ``curve_correlation(est, ref, window=m)``;
- ``normalized_weighted_curve_error(est, ref, weighted_point_weights(times,
  "uniform" | "event_density", ..., support_mask=m))`` ->
  ``nwiae(est, ref, times, weights=None | density, window=m)``;
- ``high_importance_overlap(est, ref, 0.8, m)`` -> ``high_importance_iou(est, ref, window=m)``;
- ``peak_time_error(times, est, ref, m)`` -> ``peak_time_error(est, ref, times, window=m)``;
- ``_safe_corr("spearman" | "pearson", a, b)`` -> ``rank_correlation(a, b, method)``;
- the original values in undefined cases -> the same functions with ``legacy_parity=True``;
- ``truth.integrate_curve(curve, times, support_mask=m)`` ->
  ``integrate(result, "trapezoid", window=m)``.

Tolerance: L0 (``tests/parity/tolerances.toml``). The trapezoid weights are
computed as ``(t[k+1] - t[k-1]) / 2`` here and as the sum of two half-gaps in
the original, which can differ in the last bit; everything else uses the same
operations.
"""

from __future__ import annotations

import warnings
from pathlib import Path

import numpy as np
import pytest

from timesage import TimeSAGEResult, integrate
from timesage.metrics import (
    curve_correlation,
    high_importance_iou,
    nwiae,
    peak_time_error,
    rank_correlation,
    stable_window,
)

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "metrics_legacy.npz"

# Must equal [L0_exact] in tests/parity/tolerances.toml
# (checked in tests/characterisation/test_ipcw.py).
L0_RTOL = 1e-10
L0_ATOL = 1e-12


@pytest.fixture(scope="module")
def golden() -> dict[str, np.ndarray]:
    with np.load(GOLDEN) as z:
        return {k: z[k] for k in z.files}


def _assert_l0(actual: object, expected: np.ndarray) -> None:
    np.testing.assert_allclose(np.asarray(actual), expected, rtol=L0_RTOL, atol=L0_ATOL)


def test_stable_window_matches_legacy(golden: dict[str, np.ndarray]) -> None:
    mask = stable_window(
        golden["times"],
        golden["T_test"],
        golden["E_test"],
        censoring_time=golden["T_train"],
        censoring_event=golden["E_train"],
        legacy_parity=True,
    )
    np.testing.assert_array_equal(mask, golden["mask"])


@pytest.mark.parametrize("region", ["full", "stable"])
def test_curve_metrics_match_legacy(golden: dict[str, np.ndarray], region: str) -> None:
    times, density = golden["times"], golden["density"]
    window = golden["mask"] if region == "stable" else None
    got: dict[str, list[float]] = {
        "corr": [], "nwiae_uniform": [], "nwiae_density": [], "iou": [], "peak": [],
    }  # fmt: skip
    iou_default = []
    with warnings.catch_warnings():
        warnings.simplefilter("error")  # every case except the IoU below is defined
        for est, ref in zip(golden["est"], golden["ref"], strict=True):
            got["corr"].append(curve_correlation(est, ref, window=window))
            got["nwiae_uniform"].append(nwiae(est, ref, times, window=window))
            got["nwiae_density"].append(nwiae(est, ref, times, weights=density, window=window))
            got["iou"].append(high_importance_iou(est, ref, window=window, legacy_parity=True))
            got["peak"].append(peak_time_error(est, ref, times, window=window))
    for est, ref in zip(golden["est"], golden["ref"], strict=True):
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            iou_default.append(high_importance_iou(est, ref, window=window))
    for name, values in got.items():
        _assert_l0(values, golden[f"{name}_{region}"])

    # Some humps peak outside the window, so both high-importance regions are
    # empty inside it: the original gives 0, the default gives NaN.
    legacy_iou, default_iou = golden[f"iou_{region}"], np.array(iou_default)
    undefined = np.isnan(default_iou)
    np.testing.assert_array_equal(legacy_iou[undefined], 0.0)
    _assert_l0(default_iou[~undefined], legacy_iou[~undefined])
    if region == "full":
        assert not undefined.any()


def test_rank_correlation_matches_legacy(golden: dict[str, np.ndarray]) -> None:
    pairs = list(zip(golden["int_est"], golden["int_ref"], strict=True))
    _assert_l0([rank_correlation(a, b) for a, b in pairs], golden["spearman"])
    _assert_l0([rank_correlation(a, b, "pearson") for a, b in pairs], golden["pearson"])


def test_undefined_cases_reproduce_legacy_with_parity(golden: dict[str, np.ndarray]) -> None:
    times, est, ref = golden["times"], golden["est"][0], golden["ref"][0]
    neg = -np.abs(ref)
    empty = np.zeros(len(times), dtype=bool)
    cases = {
        "iou_both_regions_empty": lambda lp: high_importance_iou(neg, neg - 0.01, legacy_parity=lp),
        "iou_empty_window": lambda lp: high_importance_iou(
            est, ref, window=empty, legacy_parity=lp
        ),
        "nwiae_zero_reference": lambda lp: nwiae(
            est, np.zeros(len(times)), times, legacy_parity=lp
        ),
        "nwiae_empty_window": lambda lp: nwiae(est, ref, times, window=empty, legacy_parity=lp),
    }
    for name, fn in cases.items():
        _assert_l0(fn(True), golden[f"undefined/{name}"])
        with pytest.warns(UserWarning, match="undefined"):
            assert np.isnan(fn(False)), name


def _result_from_curves(phi: np.ndarray, times: np.ndarray) -> TimeSAGEResult:
    p, K = phi.shape
    return TimeSAGEResult(
        phi=phi,
        phi_se=np.zeros((p, K)),
        times=times,
        feature_names=[f"f{j}" for j in range(p)],
        censoring_survival=np.ones(K),
        at_risk_fraction=np.ones(K),
        loss_empty=np.zeros(K),
        loss_full=np.zeros(K),
        n_permutations=1,
        converged=None,
        convergence_ratio=0.0,
        random_state=0,
    )


def test_windowed_integration_matches_legacy_integrate_curve(golden: dict[str, np.ndarray]) -> None:
    # The original truth.integrate_curve(curve, times, support_mask=mask), as
    # used for the synthetic study's Spearman -> integrate(result, "trapezoid", window=mask).
    times, mask = golden["times"], golden["mask"]
    starts = range(0, len(golden["est"]) - 6, 3)
    est = [
        integrate(_result_from_curves(golden["est"][j : j + 6], times), "trapezoid", window=mask)
        for j in starts
    ]
    ref = [
        _result_from_curves(golden["ref"][j : j + 6], times).integrated("trapezoid", window=mask)
        for j in starts
    ]
    _assert_l0([s.to_numpy() for s in est], golden["int_est"])
    _assert_l0([s.to_numpy() for s in ref], golden["int_ref"])
    spearman = [rank_correlation(a.to_numpy(), b.to_numpy()) for a, b in zip(est, ref, strict=True)]
    _assert_l0(spearman, golden["spearman"])

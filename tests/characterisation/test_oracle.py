"""``oracle_importance`` against the original synthetic study's oracle.

Goldens: ``tests/fixtures/golden/oracle_legacy.*``, one cell per scenario (seed
101), generated by running the original research implementation's
``oracle_runner``.

- ``legacy_parity=True`` must match the goldens at L0 (``slow``, about 40 s).
- The default (exact survival) is compared with the same goldens and the gap
  is REPORTED, not asserted: it is a documented departure.
- The oracle's standardiser must equal scikit-learn's ``StandardScaler`` at
  ``[SCALER_np_vs_sklearn]`` (fast; skipped without scikit-learn).
"""

from __future__ import annotations

import sys
import warnings
from pathlib import Path
from typing import Any

import numpy as np
import pytest

from tests.fixtures.synthetic_digest import SEEDS
from timesage.datasets.synthetic import (
    FEATURE_NAMES,
    SCENARIOS,
    _Standardiser,
    make_synthetic,
    oracle_importance,
)

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "oracle_legacy.npz"
TOLERANCES = Path(__file__).resolve().parents[1] / "parity" / "tolerances.toml"

# Must equal [L0_exact] and [SCALER_np_vs_sklearn] in tests/parity/tolerances.toml.
L0_RTOL, L0_ATOL = 1e-10, 1e-12
SCALER_RTOL, SCALER_ATOL = 0.0, 0.0


@pytest.fixture(scope="module")
def golden() -> dict[str, np.ndarray]:
    with np.load(GOLDEN) as z:
        return {k: z[k] for k in z.files}


@pytest.mark.skipif(sys.version_info < (3, 11), reason="tomllib needs Python 3.11")
def test_tolerance_constants_match_tolerances_toml() -> None:
    import tomllib

    levels = tomllib.loads(TOLERANCES.read_text(encoding="utf-8"))
    assert (levels["L0_exact"]["rtol"], levels["L0_exact"]["atol"]) == (L0_RTOL, L0_ATOL)
    scaler = levels["SCALER_np_vs_sklearn"]
    assert (scaler["rtol"], scaler["atol"]) == (SCALER_RTOL, SCALER_ATOL)


def test_standardiser_matches_sklearn() -> None:
    sklearn_pre = pytest.importorskip("sklearn.preprocessing")
    for scenario in SCENARIOS:
        for seed in SEEDS:
            X = make_synthetic(scenario, seed).train[list(FEATURE_NAMES)].to_numpy()
            ours, theirs = _Standardiser(X), sklearn_pre.StandardScaler().fit(X)
            np.testing.assert_allclose(ours.mean, theirs.mean_, rtol=SCALER_RTOL, atol=SCALER_ATOL)
            np.testing.assert_allclose(
                ours.scale, theirs.scale_, rtol=SCALER_RTOL, atol=SCALER_ATOL
            )
            Z = ours.transform(X)
            np.testing.assert_allclose(Z, theirs.transform(X), rtol=SCALER_RTOL, atol=SCALER_ATOL)
            np.testing.assert_allclose(
                ours.inverse_transform(Z),
                theirs.inverse_transform(Z),
                rtol=SCALER_RTOL,
                atol=SCALER_ATOL,
            )


def _oracle(scenario: str, legacy_parity: bool) -> Any:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # G_hat < 0.05 near 240 months in some cells
        return oracle_importance(make_synthetic(scenario, 101), legacy_parity=legacy_parity)


@pytest.mark.slow
@pytest.mark.parametrize("scenario", SCENARIOS)
def test_legacy_parity_matches_legacy_oracle(scenario: str, golden: dict) -> None:
    oracle = _oracle(scenario, legacy_parity=True)
    np.testing.assert_array_equal(oracle.times, golden[f"{scenario}/times"])
    np.testing.assert_array_equal(oracle.stable_window, golden[f"{scenario}/stable_window"])
    np.testing.assert_allclose(oracle.phi, golden[f"{scenario}/phi"], rtol=L0_RTOL, atol=L0_ATOL)
    np.testing.assert_allclose(
        oracle.integrated.to_numpy(), golden[f"{scenario}/integrated"], rtol=L0_RTOL, atol=L0_ATOL
    )


@pytest.mark.slow
@pytest.mark.parametrize("scenario", SCENARIOS)
def test_exact_oracle_gap_to_legacy_is_reported(
    scenario: str, golden: dict, record_property: Any
) -> None:
    """Report, do not assert, how far the exact oracle is from the original one."""
    oracle = _oracle(scenario, legacy_parity=False)
    legacy = golden[f"{scenario}/phi"]
    assert oracle.phi.shape == legacy.shape
    gap = {
        "max_abs_dphi": float(np.abs(oracle.phi - legacy).max()),
        "max_phi_se": float(oracle.phi_se.max()),
        "x1_curve_corr": float(np.corrcoef(oracle.phi[0], legacy[0])[0, 1]),
        "max_abs_dintegrated": float(
            np.abs(oracle.integrated.to_numpy() - golden[f"{scenario}/integrated"]).max()
        ),
    }
    for k, v in gap.items():
        record_property(k, v)
        assert np.isfinite(v)
    print(f"\n{scenario}/101 exact vs original oracle: {gap}")

"""Characterisation of ``timesage.integrate`` against the original ``integrated_importance``.

Goldens: ``tests/fixtures/golden/integrate_legacy.npz`` (metadata in the
``.json`` sidecar), generated by running the original research
implementation: the original
``TimeSAGE(...).fit(...)`` then ``integrated_importance(method=m)`` for all
three variants, on an even grid and on an uneven grid of observed times.

Mapping: ``integrated_importance(method=m)`` ->
``TimeSAGE(...).explain(...).integrated(m, legacy_parity=True)``.
With ``legacy_parity=False`` only ``at_risk`` changes, and only where a
grid time equals an observed time, which every time of the ``ties`` grid does.

Tolerance: L0 (``tests/parity/tolerances.toml``). The weights and the
reduction use the same expressions as the original implementation, so the outputs are bit-identical
in practice.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from tests.fixtures.toy_models import toy_predict_survival
from timesage import TimeSAGE, TimeSAGEResult, integrate

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "integrate_legacy.npz"
METHODS = ("trapezoid", "at_risk", "censoring")

# Must equal [L0_exact] in tests/parity/tolerances.toml
# (checked in tests/characterisation/test_ipcw.py).
L0_RTOL = 1e-10
L0_ATOL = 1e-12


@pytest.fixture(scope="module")
def golden() -> dict[str, np.ndarray]:
    with np.load(GOLDEN) as z:
        return {k: z[k] for k in z.files}


def _result(golden: dict[str, np.ndarray], grid: str) -> TimeSAGEResult:
    explainer = TimeSAGE(
        toy_predict_survival,
        background=golden["background"],
        n_permutations=128,
        batch_size=64,
        random_state=5,
    )
    return explainer.explain(golden["X"], golden["T"], golden["delta"], golden[f"{grid}/times"])


@pytest.mark.parametrize("grid", ["even", "ties"])
@pytest.mark.parametrize("method", METHODS)
def test_legacy_parity_matches_legacy_integrated_importance(
    golden: dict[str, np.ndarray], grid: str, method: str
) -> None:
    res = _result(golden, grid)
    np.testing.assert_allclose(res.phi, golden[f"{grid}/values"], rtol=L0_RTOL, atol=L0_ATOL)
    out = res.integrated(method, legacy_parity=True)  # type: ignore[arg-type]
    np.testing.assert_allclose(
        out.to_numpy(), golden[f"{grid}/{method}"], rtol=L0_RTOL, atol=L0_ATOL
    )
    assert out.equals(integrate(res, method, legacy_parity=True))  # type: ignore[arg-type]


@pytest.mark.parametrize("grid", ["even", "ties"])
@pytest.mark.parametrize("method", ["trapezoid", "censoring"])
def test_default_matches_legacy_where_ki7_does_not_apply(
    golden: dict[str, np.ndarray], grid: str, method: str
) -> None:
    out = _result(golden, grid).integrated(method)  # type: ignore[arg-type]
    np.testing.assert_allclose(
        out.to_numpy(), golden[f"{grid}/{method}"], rtol=L0_RTOL, atol=L0_ATOL
    )


def test_default_at_risk_matches_legacy_without_ties(golden: dict[str, np.ndarray]) -> None:
    times, T = golden["even/times"], golden["T"]
    assert not np.isin(times, T).any()
    out = _result(golden, "even").integrated("at_risk")
    np.testing.assert_allclose(out.to_numpy(), golden["even/at_risk"], rtol=L0_RTOL, atol=L0_ATOL)


def test_default_at_risk_differs_from_legacy_at_ties(golden: dict[str, np.ndarray]) -> None:
    # Every grid time is an observed time, so 1{Y >= t} > 1{Y > t} there.
    res = _result(golden, "ties")
    assert np.all(res.at_risk_fraction > res._at_risk_fraction_legacy)  # type: ignore[operator]
    assert not np.allclose(res.integrated("at_risk").to_numpy(), golden["ties/at_risk"])

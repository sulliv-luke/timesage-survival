"""``make_synthetic`` reproduces the original synthetic study's datasets.

Goldens (``tests/fixtures/golden/synthetic_legacy.*``) come from the 50
datasets generated by the original research implementation; no data rows are
stored beyond the first 5 training rows of seed 101 per scenario.

- Every dataset's event counts, column sums and sums of squares, per split,
  must match at ``[SYNTH_summary]`` of ``tests/parity/tolerances.toml``.
- The first rows must match at ``[SYNTH_rows]``.
- With ``TIMESAGE_EXACT_DIGESTS=1``, every dataset's SHA-256
  (``tests/fixtures/synthetic_digest.py``) must also match. This bit-exact check
  is opt-in because CPU-dependent BLAS kernels in ``multivariate_normal``
  change the last bits on other machines (it fails on CI runners), without
  any change to the generator's logic.
- With ``$TIMESAGE_SYNTHETIC_DIR`` pointing at those parquet files and pyarrow
  installed, the datasets are also compared with them directly (``needs_data``).
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import numpy as np
import pytest

from tests.fixtures.synthetic_digest import (
    FLOAT_COLUMNS,
    LEGACY_NAMES,
    SEEDS,
    dataset_digest,
    dataset_summary,
    legacy_filename,
)
from timesage.datasets.synthetic import SCENARIOS, make_synthetic

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "synthetic_legacy"
TOLERANCES = Path(__file__).resolve().parents[1] / "parity" / "tolerances.toml"
GENERATED = Path(os.environ.get("TIMESAGE_SYNTHETIC_DIR", "generated"))

# Must equal [SYNTH_rows] in tests/parity/tolerances.toml (checked below on 3.11+).
ROWS_RTOL = 1e-12
ROWS_ATOL = 1e-12
# Must equal [SYNTH_summary] in tests/parity/tolerances.toml (checked below on 3.11+).
SUMMARY_RTOL = 1e-10
SUMMARY_ATOL = 1e-10

_META = json.loads(GOLDEN.with_suffix(".json").read_text(encoding="utf-8"))
DIGESTS: dict[str, str] = _META["digests"]
SUMMARIES: dict[str, dict[str, list[float]]] = _META["summaries"]


@pytest.mark.skipif(sys.version_info < (3, 11), reason="tomllib needs Python 3.11")
def test_tolerance_constants_match_tolerances_toml() -> None:
    import tomllib

    levels = tomllib.loads(TOLERANCES.read_text(encoding="utf-8"))
    rows, summary = levels["SYNTH_rows"], levels["SYNTH_summary"]
    assert (rows["rtol"], rows["atol"]) == (ROWS_RTOL, ROWS_ATOL)
    assert (summary["rtol"], summary["atol"]) == (SUMMARY_RTOL, SUMMARY_ATOL)


def test_golden_covers_the_study() -> None:
    assert len(DIGESTS) == 50
    assert set(SUMMARIES) == set(DIGESTS)
    assert {k.split("/")[0] for k in DIGESTS} == set(SCENARIOS)


@pytest.mark.parametrize("scenario", SCENARIOS)
def test_first_rows_match_legacy(scenario: str) -> None:
    with np.load(GOLDEN.with_suffix(".npz")) as z:
        rows, events = z[f"{scenario}/first_rows"], z[f"{scenario}/first_events"]
    train = make_synthetic(scenario, seed=101).train
    np.testing.assert_allclose(
        train.loc[: len(rows) - 1, list(FLOAT_COLUMNS)].to_numpy(),
        rows,
        rtol=ROWS_RTOL,
        atol=ROWS_ATOL,
    )
    np.testing.assert_array_equal(train.loc[: len(rows) - 1, "event"].to_numpy(), events)


@pytest.mark.parametrize("key", sorted(SUMMARIES))
def test_dataset_summary_matches_legacy(key: str) -> None:
    scenario, seed = key.split("/")
    data = make_synthetic(scenario, seed=int(seed))
    ours = dataset_summary([data.train, data.validation, data.test])
    for split, reference in SUMMARIES[key].items():
        np.testing.assert_array_equal(ours[split][0], reference[0])  # event count: exact
        np.testing.assert_allclose(
            ours[split][1:], reference[1:], rtol=SUMMARY_RTOL, atol=SUMMARY_ATOL
        )


@pytest.mark.parametrize("key", sorted(DIGESTS))
def test_dataset_digest_matches_legacy(key: str) -> None:
    if os.environ.get("TIMESAGE_EXACT_DIGESTS") != "1":
        pytest.skip("bit-exact digest is machine-dependent; set TIMESAGE_EXACT_DIGESTS=1")
    scenario, seed = key.split("/")
    data = make_synthetic(scenario, seed=int(seed))
    assert dataset_digest([data.train, data.validation, data.test]) == DIGESTS[key]


@pytest.mark.needs_data
@pytest.mark.parametrize("scenario", SCENARIOS)
def test_matches_legacy_parquet_files(scenario: str) -> None:
    if "TIMESAGE_SYNTHETIC_DIR" not in os.environ or not GENERATED.exists():
        pytest.skip(f"needs_data: missing {GENERATED} (set TIMESAGE_SYNTHETIC_DIR)")
    pd = pytest.importorskip("pandas")
    pytest.importorskip("pyarrow")
    for seed in SEEDS:
        combined = pd.read_parquet(GENERATED / legacy_filename(scenario, seed))
        combined = combined.rename(columns=LEGACY_NAMES)
        data = make_synthetic(scenario, seed=seed)
        for split, ours in (
            ("train", data.train),
            ("validation", data.validation),
            ("test", data.test),
        ):
            theirs = combined.loc[combined["split"] == split].drop(columns=["split"])
            pd.testing.assert_frame_equal(
                ours, theirs.reset_index(drop=True)[list(ours.columns)], check_exact=True
            )
